/**
 * Rubro (industry category) a client factory belongs to: Metalúrgica,
 * Autopartes, Agroindustria, and so on. It is its own catalog in the ERS
 * (CU-41 Registrar / CU-42 Modificar / CU-43 Consultar / CU-44 Baja de Rubro)
 * and the `Categories` module of the API contract.
 *
 * Shape mirrors `docs/openapi/components/schemas/Category.yaml` exactly.
 *
 * NOTE: the customers feature still carries a parallel `Industry` type pointing
 * at `/industries` with a string id. This one follows the contract and is meant
 * to replace it once the factory form is migrated (separate PR).
 */
export interface Category {
  /** Autogenerated by the backend (`integer` in the contract, not a string). */
  id: number
  /** Short name, 1-80 characters. Unique across the system. */
  name: string
  /** Creation timestamp, ISO 8601. Read-only. */
  createdAt: string
  /** Last modification timestamp, ISO 8601. Read-only. */
  updatedAt: string
}

/**
 * Payload sent to the API on create (`CategoryCreate`) and on update
 * (`CategoryUpdate`). The contract declares every field optional on update but
 * requires at least one; since `name` is the only field, the same shape serves
 * both operations.
 */
export interface CategoryInput {
  name: string
}
