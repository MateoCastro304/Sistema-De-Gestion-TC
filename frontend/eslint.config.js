import js from '@eslint/js'
import globals from 'globals'
import reactHooks from 'eslint-plugin-react-hooks'
import reactRefresh from 'eslint-plugin-react-refresh'
import tseslint from 'typescript-eslint'
import { defineConfig, globalIgnores } from 'eslint/config'

/**
 * Frontend ESLint config (React + Vite, organized by features).
 *
 * Principles:
 * - Every rule is 'error' or 'off'. The lint script runs with
 *   --max-warnings 0, so plugin rules that default to 'warn' also fail CI.
 * - Type-aware linting (recommendedTypeChecked): catches unhandled promises,
 *   the most common bug in a SPA built on React Query and react-hook-form.
 * - What tsc already checks (type-only imports, unused locals) is not repeated here.
 */

// Internal folders of a feature. From outside, a feature is only reached through its index.ts.
const featureInternals = '^@/features/.+/(api|components|pages|schemas|types|utils)(/|$)'

export default defineConfig([
  globalIgnores([
    'dist',
    'coverage',
    // Generated by MSW (`msw init`) and regenerated on every npm install: never edited or linted.
    'public/mockServiceWorker.js',
  ]),
  {
    linterOptions: {
      reportUnusedDisableDirectives: 'error',
    },
  },

  // --- Application code ----------------------------------------------------
  {
    files: ['src/**/*.{ts,tsx}'],
    extends: [
      js.configs.recommended,
      tseslint.configs.recommendedTypeChecked,
      reactHooks.configs.flat.recommended,
      reactRefresh.configs.vite,
    ],
    languageOptions: {
      globals: globals.browser,
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      '@typescript-eslint/no-misused-promises': [
        'error',
        // onSubmit={handleSubmit(fn)} and onClick={async () => ...} are the normal
        // React pattern: the handler returns a promise that React ignores.
        // Everything else is still checked (e.g. a promise used as an if condition).
        { checksVoidReturn: { attributes: false } },
      ],
      '@typescript-eslint/no-unused-vars': [
        'error',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_', caughtErrorsIgnorePattern: '^_' },
      ],
    },
  },

  // --- Layer boundaries ----------------------------------------------------
  // app/      -> composition (router, providers, layout). May use everything.
  // features/ -> one module per business area. Uses shared/ and domain/, and other
  //              features only through their index.ts. From app/ it may only use
  //              app/providers (contexts: notifications, user).
  // shared/   -> reusable, no business logic. Knows nothing about features or app.
  // domain/   -> shared business types/rules. Knows nothing else.
  // To leave your folder use the @/ alias, never ../../
  {
    files: ['src/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: ['../../*'],
              message: 'To leave your folder use the @/ alias (so the layer rules can see the import).',
            },
            {
              regex: featureInternals,
              message: 'Import the feature through its index.ts (@/features/...), not its internal files.',
            },
          ],
        },
      ],
    },
  },
  {
    // app/mocks gathers each feature's *.mocks.ts and is the only exception to
    // "go through index.ts": if mocks were exported from the index, MSW and the
    // fake data would end up in the production bundle.
    files: ['src/app/mocks/**/*.ts'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            {
              group: ['../../*'],
              message: 'To leave your folder use the @/ alias (so the layer rules can see the import).',
            },
          ],
        },
      ],
    },
  },
  {
    files: ['src/features/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            { group: ['../../*'], message: 'To leave your folder use the @/ alias.' },
            {
              regex: featureInternals,
              message: 'Import the feature through its index.ts (@/features/...), not its internal files.',
            },
            {
              // The negation lets app/providers through: those are the contexts
              // (notifications, user) that features consume through hooks.
              group: ['@/app/*', '!@/app/providers'],
              message:
                'A feature may only use app/providers from app/. If several features need it, move it to shared/.',
            },
          ],
        },
      ],
    },
  },
  {
    files: ['src/shared/**/*.{ts,tsx}', 'src/domain/**/*.{ts,tsx}'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            { group: ['../../*'], message: 'To leave your folder use the @/ alias.' },
            {
              group: ['@/app/*', '@/features/*'],
              message: 'shared/ and domain/ must not depend on app/ or features/.',
            },
          ],
        },
      ],
    },
  },

  {
    // The *.mocks.ts files are a fake backend. Like backend modules, they may
    // read each other's tables (`api/*.db.ts`) and types: a factory needs its
    // rubro to exist, a user needs its employee. They are only loaded from
    // app/mocks in dev, so this coupling never reaches the production bundle.
    files: ['src/features/**/api/*.mocks.ts', 'src/features/**/api/*.db.ts'],
    rules: {
      'no-restricted-imports': [
        'error',
        {
          patterns: [
            { group: ['../../*'], message: 'To leave your folder use the @/ alias.' },
            {
              regex: '^@/features/.+/(api/(?!.+\\.db$)|components|pages|schemas|utils)',
              message: 'A mock may only read other features through their api/*.db.ts and types/.',
            },
            {
              group: ['@/app/*'],
              message: 'Mocks must not depend on app/.',
            },
          ],
        },
      ],
    },
  },

  // --- Tooling config (Node, not browser) ----------------------------------
  {
    // E2E tests (Playwright) and their config run in Node, not in the app.
    files: ['playwright.config.ts', 'e2e/**/*.ts'],
    extends: [js.configs.recommended, tseslint.configs.recommendedTypeChecked],
    languageOptions: {
      globals: globals.node,
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
    rules: {
      // Playwright fixtures destructure `{}` when they need nothing.
      'no-empty-pattern': 'off',
    },
  },
  {
    files: ['vite.config.ts'],
    extends: [js.configs.recommended, tseslint.configs.recommendedTypeChecked],
    languageOptions: {
      globals: globals.node,
      parserOptions: {
        projectService: true,
        tsconfigRootDir: import.meta.dirname,
      },
    },
  },
  {
    files: ['**/*.{js,mjs,cjs}'],
    extends: [js.configs.recommended],
    languageOptions: {
      globals: globals.node,
    },
  },
])
