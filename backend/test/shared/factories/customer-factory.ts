import { faker } from '@faker-js/faker';
import { getPrisma } from '../harness/test-app';
import { createFactory } from './factory-factory';

export interface CustomerPayload {
  name: string;
  lastName: string;
  phone: string;
  mail: string;
  factoryId: number;
}

export function aCustomer(overrides: Partial<CustomerPayload> = {}) {
  return {
    name: faker.person.firstName(),
    lastName: faker.person.lastName(),
    phone: '+54 9 351 444-5678',
    mail: faker.internet.email(),
    factoryId: 1,
    ...overrides,
  };
}

type OverridesCustomer = {
  name?: string;
  lastName?: string;
  phone?: string;
  mail?: string;
  factoryId?: number;
  isActive?: boolean;
};

/**
 * Seeds a Customer row directly through Prisma. `id` is per-factory and
 * normally generated by the `fn_gen_id_manager` DB trigger; here it is
 * picked at random since Prisma has no default configured for it.
 * When no `factoryId` is given, a Factory is created first (FK constraint).
 */
export async function createCustomer(overrides: OverridesCustomer = {}) {
  const factoryId = overrides.factoryId ?? (await createFactory()).id;

  return getPrisma().customer.create({
    data: {
      id: faker.number.int({ min: 1, max: 1_000_000 }),
      factoryId,
      name: overrides.name ?? faker.person.firstName(),
      lastName: overrides.lastName ?? faker.person.lastName(),
      phone: overrides.phone ?? '+54 9 351 444-5678',
      mail: overrides.mail ?? faker.internet.email(),
      isActive: overrides.isActive ?? true,
    },
  });
}
